import assert from 'node:assert/strict';
import { measureNativeLayout as measure,compare,settle,noFilters } from './layout-parity.mjs';

export async function runReferenceChecks({cdp,base,until}) {
  const page=await cdp.page(`${base}/minimalist.html`);
  await page.activate();
  await until(page,'document.documentElement.dataset.bcPage === "home"');
  const css=(selector,property)=>page.evaluate(`getComputedStyle(document.querySelector(${JSON.stringify(selector)}))[${JSON.stringify(property)}]`);
  const patch=async changes=>{
    const response=await page.evaluate(`chrome.runtime.sendMessage({type:'BC_THEME/PATCH',payload:${JSON.stringify(changes)}})`);
    assert.equal(response.ok,true);
    await until(page, changes.enabled===false?'!document.documentElement.hasAttribute("data-bc-enabled")':
      `document.documentElement.getAttribute('data-bc-min-options') === BiliThemeMinimalist.flags(${JSON.stringify(response.data.settings)}) && document.documentElement.style.getPropertyValue('--bc-text-color') === '${response.data.settings.textColor}'`);
    await settle(page);
  };
  await patch({...noFilters,enabled:false,minimalistEnabled:false});
  const native=await measure(page);
  const before=(await page.evaluate("chrome.runtime.sendMessage({type:'BC_THEME/GET'})")).data;
  const popup=await cdp.page(`${base}/popup.html`);
  await until(popup,'!document.querySelector("#controls").disabled');
  await popup.evaluate('document.querySelector("#apply-reference").click()');
  await until(page,'document.documentElement.dataset.bcMinOptions?.includes("reference") && document.documentElement.dataset.bcEnabled==="true"');
  await until(popup,'!document.querySelector("#reset").disabled');
  assert.equal(await popup.evaluate('document.querySelector("[name=minimalistReferenceLayout]").checked'),true);
  assert.equal(await popup.evaluate('document.querySelector("[name=minimalistGrid]")'),null,'retired geometry controls are not exposed');
  const after=(await page.evaluate("chrome.runtime.sendMessage({type:'BC_THEME/GET'})")).data;
  for(const key of Object.keys(noFilters).concat(['minimalistEnabled','minimalistGrid','minimalistCompactNav']))assert.equal(after.settings[key],before.settings[key],key);
  assert.deepEqual(after.background,before.background);
  await popup.close();await page.activate();await settle(page);
  compare(native,await measure(page),'visual preset retains outer geometry',{cardStretch:true});
  assert.match(await css('#bc-theme-wallpaper','backgroundImage'),/radial-gradient/);
  await patch({textColor:'#ffffff'});
  assert.equal(await page.evaluate('document.documentElement.style.getPropertyValue("--bc-text-color")'),'#ffffff');
  assert.equal(await css('#normal h3 a','color'),'rgb(255, 255, 255)','light wallpaper strengthens tint and retains white foreground');
  await patch({textColor:'#232638'});
  assert.match(await css('#bc-theme-header-glass','backdropFilter'),/blur\(15px\).*saturate/);
  assert.equal(await css('#normal .bili-video-card__info','backdropFilter'),'none');
  assert.equal(await css('#normal .bili-video-card__info','backgroundImage'),'none');
  assert.equal(await page.evaluate('originalCards.every(n=>n.isConnected&&document.getElementById(n.id)===n)'),true);
  await page.evaluate(`document.querySelector('#logo').click();document.querySelector('#normal h3 a').click();document.querySelector('#avatar').click();document.querySelector('#search').dispatchEvent(new Event('input'));`);
  assert.equal(await page.evaluate('actions.links'),2);
  for(const selector of ['.nav-search-panel','.v-popover-content'])assert.notEqual(await css(selector,'display'),'none');
  await patch({material:'clear'});
  assert.equal(await page.evaluate('document.querySelector("#bc-theme-header-glass")'),null);
  await patch({material:'glass'});
  const gif='data:image/gif;base64,R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7';
  await page.evaluate(`chrome.runtime.sendMessage({type:'BC_THEME/BACKGROUND',payload:{dataUrl:'${gif}',name:'Keep my background'}})`);
  await until(page,'document.querySelector("#bc-theme-wallpaper")?.dataset.bcCustom === "true"');
  assert.match(await css('#bc-theme-wallpaper','backgroundImage'),/url\(/);
  await page.evaluate("chrome.runtime.sendMessage({type:'BC_THEME/BACKGROUND',payload:null})");
  await patch({minimalistReferenceLayout:false});
  assert.doesNotMatch(await css('#bc-theme-wallpaper','backgroundImage'),/radial-gradient/);
  await patch({minimalistReferenceLayout:true});
  await page.reload();
  await until(page,'document.documentElement.dataset.bcMinOptions?.includes("reference")');
  assert.equal(await page.evaluate('document.documentElement.hasAttribute("data-bc-minimalist")'),false,'appearance works independently of filters');
  await page.evaluate("history.pushState({},'', '/video/BV-reference')");
  await until(page,'document.documentElement.dataset.bcPage === "video"');
  assert.doesNotMatch(await css('#bc-theme-wallpaper','backgroundImage'),/radial-gradient/,'home palette is route scoped');
  await page.evaluate("chrome.runtime.sendMessage({type:'BC_THEME/RESET'})");
  await page.close();
  console.log('  PASS appearance preset: native geometry, existing filter/media preferences, retired controls, interactions, Clear, palette, persistence and route isolation');
}
